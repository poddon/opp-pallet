CREATE TABLE IF NOT EXISTS results (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 date TEXT NOT NULL, name TEXT NOT NULL, name_norm TEXT NOT NULL,
 group_code TEXT NOT NULL, modules TEXT NOT NULL, status TEXT NOT NULL,
 correct INTEGER NOT NULL, total INTEGER NOT NULL, pct INTEGER NOT NULL,
 xp INTEGER NOT NULL, duration INTEGER NOT NULL,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_results_name ON results(name_norm,status);
CREATE TABLE IF NOT EXISTS grants (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 name_norm TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
